"""Generates SOURCES.md from config/thresholds.yaml + protocol files, so the list can never drift
from the numbers the app actually uses. Run from backend/:  python scripts/gen_sources.py"""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.config import THRESHOLDS_PATH, iter_entries  # noqa: E402
from app.engine.protocols import PROTOCOL_DIR  # noqa: E402

th = yaml.safe_load(THRESHOLDS_PATH.read_text())
entries = list(iter_entries(th))
verified = [e for e in entries if e[1]["status"] == "VERIFIED"]
assumptions = [e for e in entries if e[1]["status"] == "ASSUMPTION"]
esc = lambda s: str(s).replace("|", "\\|")

out = ["# Sources and assumptions", "",
       "> Generated by `backend/scripts/gen_sources.py` from `backend/config/thresholds.yaml`. Do not edit by hand. Edit the YAML and re-run the script.", "",
       "CrewCheck uses **SIMULATED data** and is a hackathon decision-support prototype, **not a medical device**.", "",
       f"**Status:** {len(verified)} VERIFIED · **{len(assumptions)} ASSUMPTION** (of {len(entries)} configured values).", "",
       "An ASSUMPTION is a value the team has not yet checked against a primary source. The `todo` column holds a *lead* "
       "(a paper or standard to check), which is **not** a citation.", "",
       "## External data and software", "",
       "| What | Used for | Link |", "|---|---|---|",
       "| NASA DONKI (Space Weather Database Of Notifications, Knowledge, Information), FLR and SEP endpoints via api.nasa.gov | Solar flare / solar energetic particle feed in the Radiation panel (cached; offline sample bundled) | https://api.nasa.gov · https://ccmc.gsfc.nasa.gov/tools/DONKI/ |",
       "| Chart.js 4.4.7 (MIT) | Live vitals chart, served locally from `frontend/vendor/` | https://www.chartjs.org |",
       "| Challenge statement: NASA Space Apps Challenge 2026 | Problem definition | https://www.spaceappschallenge.org |", "",
       "TODO: add the links from the challenge **Resources** tab once available.", "",
       "## Verified values", ""]
if verified:
    out += ["| Key | Value | Source |", "|---|---|---|"]
    out += [f"| `{k}` | {e['value']} {esc(e['unit'])} | [{esc(e['source_title'])}]({e['source_url']}) |" for k, e in verified]
else:
    out += ["_None yet._"]
out += ["", "## Assumptions (to verify)", "", "| Key | Value | Unit | TODO / lead |", "|---|---|---|---|"]
out += [f"| `{k}` | {e['value']} | {esc(e['unit'])} | {esc(e['todo'])} |" for k, e in assumptions]
out += ["", "## Action protocols", "",
        "All protocol texts in `backend/content/protocols/` are **DRAFT** content written by the team and **not medically reviewed**.", "",
        "| Protocol | Title | Review status |", "|---|---|---|"]
for f in sorted(PROTOCOL_DIR.glob("*.yaml")):
    p = yaml.safe_load(f.read_text())
    out.append(f"| `{p['id']}` | {esc(p['title'])} | {p['review_status']} |")
out += ["", "## Demo scenario", "",
        "`backend/scenarios/mars_day120.json` describes deviations in standard deviations from each crew member's own simulated baseline. "
        "Values are clamped to the simulation ranges above. The crew members are fictional.", ""]
(Path(__file__).resolve().parents[2] / "SOURCES.md").write_text("\n".join(out))
print(f"SOURCES.md written: {len(entries)} entries, {len(assumptions)} assumptions")
